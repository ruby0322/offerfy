#!/usr/bin/env bash
# Restart every Offerfy frontend instance with no downtime and no failed
# requests, by draining each one out of the load balancer before it goes down.
#
# HOW THE PATH WORKS (see docs/host-scaling-plan.md section 2.6)
#   ingress-nginx -> Service offerfy-native-3100 (targetPort 3210)
#     -> 192.168.49.1:3210  = the `web-lb` nginx container (host networking)
#        -> 127.0.0.1:3200  offerfy-web.service      (system unit)
#        -> 127.0.0.1:3201  offerfy-web@3201         (user unit)
#        -> 127.0.0.1:3202  offerfy-web@3202         (user unit)
#
# WHY THE DRAIN IS NOT OPTIONAL
# nginx retries another upstream on a connect failure, but `non_idempotent` is
# deliberately not enabled, so a POST already delivered to a dying instance is
# NOT retried -- it fails to a real user. Marking the server `down` and reloading
# first means nginx has already stopped sending it anything, and its in-flight
# requests finish on the old worker set.
#
# NEEDS NO SUDO: the units run as ruby0322, so the owning user may signal the
# main process and systemd's Restart=always brings it back (AGENTS.md section 4).
#
# Usage:
#   ops/rolling-restart-web.sh                # restart every instance
#   ops/rolling-restart-web.sh --dry-run
#   PORTS="3201 3202" ops/rolling-restart-web.sh
set -euo pipefail

REPO=/home/ruby0322/offerfy
UPSTREAM_FILE="$REPO/ops/nginx/upstream.d/offerfy-web-upstream.conf"
LB_CONTAINER=offerfy-web-lb-1
ALL_PORTS=(3200 3201 3202)
PUBLIC_URL=https://offerfy.cc/
LB_URL=http://192.168.49.1:3210/
RELOAD_SETTLE=2
BOOT_TIMEOUT=120

DRY_RUN=0
[[ "${1:-}" == "--dry-run" ]] && DRY_RUN=1

say() { printf '%s %s\n' "$(date +%H:%M:%S)" "$*"; }
die() { printf '\n!! %s\n' "$*" >&2; exit 1; }

read -r -a TARGETS <<< "${PORTS:-${ALL_PORTS[*]}}"
say "instances: ${ALL_PORTS[*]}   restarting: ${TARGETS[*]}"

# 3200 is the original *system* unit; everything else is a user unit. Disabling
# the system one would need root and there is no reason to -- it is a working
# instance. So resolve the unit per port instead of assuming one kind.
unit_kind() { [[ "$1" == "3200" ]] && echo system || echo user; }
unit_name() { [[ "$1" == "3200" ]] && echo offerfy-web || echo "offerfy-web@$1"; }

main_pid() {
  local p=$1
  if [[ "$(unit_kind "$p")" == user ]]; then
    systemctl --user show -p MainPID --value "$(unit_name "$p")" 2>/dev/null || echo 0
  else
    systemctl show -p MainPID --value "$(unit_name "$p")" 2>/dev/null || echo 0
  fi
}

# Rewrite the upstream file, optionally marking one port `down`, then reload.
# Writes to a temp file in the same directory and renames: the DIRECTORY is
# bind-mounted into the container, so a rename is visible; renaming over a
# bind-mounted *file* would instead break the mount.
set_upstreams() {
  local down="${1:-}" tmp
  tmp="$(mktemp "$(dirname "$UPSTREAM_FILE")/.upstream.XXXXXX")"
  {
    echo "# Generated by ops/rolling-restart-web.sh. The committed version has all"
    echo "# instances up; a \`down\` here means a rolling restart is in progress."
    echo "upstream offerfy_web {"
    for p in "${ALL_PORTS[@]}"; do
      if [[ "$p" == "$down" ]]; then
        echo "    server 127.0.0.1:$p max_fails=2 fail_timeout=5s down;"
      else
        echo "    server 127.0.0.1:$p max_fails=2 fail_timeout=5s;"
      fi
    done
    echo
    echo "    keepalive 32;"
    echo "}"
  } > "$tmp"
  if (( DRY_RUN )); then
    say "  [dry-run] would mark '${down:-none}' down and reload"
    command rm -f -- "$tmp"
    return
  fi
  mv "$tmp" "$UPSTREAM_FILE"
  # SIGHUP to PID 1 of the container is a graceful nginx reload: it starts new
  # workers with the new config and lets the old ones finish their connections.
  # `docker kill -s HUP` rather than `docker exec nginx -s reload` because exec
  # into this container has been observed to hang (host networking + exec).
  docker kill -s HUP "$LB_CONTAINER" >/dev/null
}

wait_until_serving() {
  local port=$1 deadline=$((SECONDS + BOOT_TIMEOUT)) code
  while (( SECONDS < deadline )); do
    code=$(curl -sS -o /dev/null -w '%{http_code}' --max-time 5 "http://127.0.0.1:$port/" 2>/dev/null || echo 000)
    [[ $code =~ ^[23] ]] && { say "  :$port answering ($code)"; return 0; }
    sleep 2
  done
  return 1
}

check() {
  local what=$1 url=$2 code
  code=$(curl -sS -o /dev/null -w '%{http_code}' --max-time 20 -L "$url" 2>/dev/null || echo 000)
  [[ $code == 200 || $code == 307 ]] \
    || die "$what returned $code. Stopping here; upstream file is $(basename "$UPSTREAM_FILE") -- inspect before continuing."
  say "  $what ok ($code)"
}

if (( ! DRY_RUN )); then
  check "lb" "$LB_URL"
  check "public site" "$PUBLIC_URL"
fi

for port in "${TARGETS[@]}"; do
  say "--- :$port ($(unit_name "$port"), $(unit_kind "$port") unit)"

  say "  draining out of the load balancer"
  set_upstreams "$port"
  sleep "$RELOAD_SETTLE"
  (( DRY_RUN )) || check "public site" "$PUBLIC_URL"

  old=$(main_pid "$port")
  if (( DRY_RUN )); then
    say "  [dry-run] would kill -TERM $old, wait for a new MainPID, then re-add"
  else
    [[ "$old" != "0" ]] || die "$(unit_name "$port") has no MainPID -- is it running?"
    say "  restarting (MainPID $old)"
    kill -TERM "$old"
    # TimeoutStopSec=20 caps the npx/next tree's ~36 s `deactivating`, but allow
    # well past that before calling it a failure.
    new=0
    for _ in $(seq 1 90); do
      new=$(main_pid "$port")
      [[ "$new" != "0" && "$new" != "$old" ]] && break
      sleep 1
    done
    [[ "$new" != "0" && "$new" != "$old" ]] \
      || die "$(unit_name "$port") did not come back with a new MainPID. It is still drained; fix it, then re-run."
    say "  new MainPID $new"
    wait_until_serving "$port" \
      || die "$(unit_name "$port") never answered on 127.0.0.1:$port. Left drained on purpose; fix it, then re-run."
  fi

  say "  re-adding to the load balancer"
  set_upstreams ""
  sleep "$RELOAD_SETTLE"
  (( DRY_RUN )) || check "public site" "$PUBLIC_URL"
done

say "done -- ${TARGETS[*]} restarted, all of ${ALL_PORTS[*]} back in rotation"
